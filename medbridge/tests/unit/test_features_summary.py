"""Clinician summary: assembly from (mocked) session data and Markdown rendering."""
import uuid
from datetime import UTC, datetime, timedelta
from unittest.mock import AsyncMock

import pytest

from medbridge.features import summary as summary_mod
from medbridge.features.summary import build_clinician_summary, render_markdown
from medbridge.state.session_manager import SessionErasedError, SessionNotFoundError
from medbridge.state.turn_store import EventRow, HistoryRow, SessionState

T0 = datetime(2026, 10, 9, 8, 0, tzinfo=UTC)


def _history() -> list[HistoryRow]:
    def row(role, content, action=None, citations=None, minutes=0):
        return HistoryRow(uuid.uuid4(), role, content, action, citations or [],
                          T0 + timedelta(minutes=minutes))

    citation = {"marker": "[1]", "chunk_id": "aha_s8_c1", "source": "AHA/ACC 2025",
                "title": "2025 AHA/ACC High Blood Pressure Guideline", "org": "AHA/ACC",
                "year": 2025, "section": "8.1 BP goals", "page": 34, "excerpt": "..."}
    return [
        row("user", "What should my BP target be? | test", minutes=0),
        row("assistant", "For most adults the goal is below 130/80 mmHg [1].", "ANSWER",
            [citation], minutes=1),
        row("user", "Can I double my Telma 40?", minutes=2),
        row("assistant", "First reply", "GENERALIZE", minutes=3),
        row("assistant", "I can't advise on dose changes; please ask your doctor.", "ABSTAIN",
            minutes=4),
    ]


@pytest.fixture
def mocked_store(monkeypatch: pytest.MonkeyPatch) -> None:
    snapshot = {
        "demographics": {"age": 58},
        "current_medications": [{"drug": "Telma", "dosage": "40mg", "frequency": "daily"}],
        "discontinued_medications": [{"drug": "Amlodipine", "dosage": "5mg", "frequency": "",
                                      "reason": "ankle swelling", "stopped_at": None}],
        "symptoms": ["headache"],
        "lab_results": [{"lab_type": "potassium", "value": 4.6, "unit": "mEq/L"}],
    }
    events = [EventRow(uuid.uuid4(), "BP_READING",
                       {"systolic": 152, "diastolic": 96, "pulse": 78}, T0)]
    monkeypatch.setattr(summary_mod.turn_store, "load_session_state",
                        AsyncMock(return_value=SessionState(snapshot=snapshot)))
    monkeypatch.setattr(summary_mod.turn_store, "get_history", AsyncMock(return_value=_history()))
    monkeypatch.setattr(summary_mod.turn_store, "list_events", AsyncMock(return_value=events))


async def test_summary_structure(mocked_store: None) -> None:
    sid = uuid.uuid4()
    data = await build_clinician_summary(AsyncMock(), sid)
    assert data["session_ref"] == str(sid)[:8]
    assert "not a diagnosis" in data["disclaimer"]
    assert [r["category"] for r in data["bp_readings"]] == ["stage2"]
    first, second = data["exchanges"]
    assert first["n"] == 1 and first["action"] == "ANSWER"
    assert first["citations"][0] == {
        "marker": "[1]", "source": "AHA/ACC 2025",
        "title": "2025 AHA/ACC High Blood Pressure Guideline", "org": "AHA/ACC", "year": 2025,
        "section": "8.1 BP goals", "page": 34, "chunk_id": "aha_s8_c1",
    }
    assert second["action"] == "ABSTAIN" and second["regenerated"] is True
    assert data["action_counts"] == {"ANSWER": 1, "ABSTAIN": 1}


async def test_markdown_rendering(mocked_store: None) -> None:
    md = render_markdown(await build_clinician_summary(AsyncMock(), uuid.uuid4()))
    assert md.startswith("# MedBridge — Clinician Summary")
    assert "> **Disclaimer:**" in md
    assert "- **Current medications:** Telma 40mg daily" in md
    assert "Amlodipine 5mg (reason: ankle swelling)" in md
    assert "| 1 | 2026-10-09T08:00:00+00:00 | 152/96 | 78 | Stage 2 hypertension | chat |" in md
    assert "### 1. `ANSWER` What should my BP target be? | test" in md
    assert "- [1] 2025 AHA/ACC High Blood Pressure Guideline — 8.1 BP goals, p. 34" in md
    assert "### 2. `ABSTAIN` Can I double my Telma 40?" in md
    assert "_(Answer regenerated by the user; latest version shown.)_" in md
    assert md.rstrip().endswith("*")


def test_empty_session_rendering() -> None:
    md = render_markdown({
        "app": "MedBridge", "session_ref": "abcd1234", "generated_at": "2026-10-09T00:00:00+00:00",
        "disclaimer": "d", "snapshot": {}, "bp_readings": [], "exchanges": [],
        "action_counts": {},
    })
    assert "No patient context was reported in this session." in md
    assert "No blood-pressure readings were recorded." in md
    assert "No questions were asked in this session." in md


async def test_missing_or_erased_session(monkeypatch: pytest.MonkeyPatch) -> None:
    load = AsyncMock(return_value=SessionState(exists=False))
    monkeypatch.setattr(summary_mod.turn_store, "load_session_state", load)
    with pytest.raises(SessionNotFoundError):
        await build_clinician_summary(AsyncMock(), uuid.uuid4())
    load.return_value = SessionState(erased=True)
    with pytest.raises(SessionErasedError):
        await build_clinician_summary(AsyncMock(), uuid.uuid4())


async def test_summary_shows_profile_brands_classes_and_dose_history(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    snapshot = {
        "demographics": {"age": 31, "sex": "female", "pregnancy_status": "pregnant",
                         "conditions": ["diabetes", "chronic kidney disease"]},
        "current_medications": [{
            "drug": "amlodipine", "dosage": "10 mg", "frequency": "once daily",
            "brand_name": "Amlong", "drug_class": "calcium channel blocker",
            "history": [{"dosage": "5 mg", "frequency": "once daily"}],
        }],
    }
    monkeypatch.setattr(summary_mod.turn_store, "load_session_state",
                        AsyncMock(return_value=SessionState(snapshot=snapshot)))
    monkeypatch.setattr(summary_mod.turn_store, "get_history", AsyncMock(return_value=[]))
    monkeypatch.setattr(summary_mod.turn_store, "list_events", AsyncMock(return_value=[]))
    data = await build_clinician_summary(AsyncMock(), uuid.uuid4())
    assert data["profile"] == {"age": 31, "sex": "female", "pregnancy_status": "pregnant",
                               "conditions": ["diabetes", "chronic kidney disease"]}
    assert data["medications"] == [{
        "drug": "amlodipine", "brand_name": "Amlong", "drug_class": "calcium channel blocker",
        "dosage": "10 mg", "frequency": "once daily",
        "history": [{"dosage": "5 mg", "frequency": "once daily"}],
    }]
    md = render_markdown(data)
    assert "- **Demographics:** age 31, sex female" in md
    assert "- **Pregnancy status:** pregnant" in md
    assert "- **Long-term conditions:** diabetes, chronic kidney disease" in md
    assert ("- **Current medications:** amlodipine (Amlong; calcium channel blocker) 10 mg "
            "once daily (previously 5 mg once daily)") in md
